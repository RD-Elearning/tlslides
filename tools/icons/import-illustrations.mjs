#!/usr/bin/env node
/**
 * spro creative PLAN CR9 — Open Doodles (Pablo Stanley, CC0; the `react-open-doodles` 1.0.5
 * wrapper is MIT) into `packages/tldraw/src/blocks/icons/illustrations.ts` for `tls.m.illustration`:
 * each scene rendered once to SVG with sentinel colours, which become palette-role slots
 * (`{ink}`, `{accent}`, `{paper}`), so a slide recolours a scene from its own palette.
 *
 *   NODE_PATH=node_modules node tools/icons/import-illustrations.mjs <react-open-doodles package dir>
 *
 * The package comes from `npm pack react-open-doodles@1.0.5` into a scratch directory; its LICENSE
 * is checked to be MIT. Only the `KEEP` scenes are imported (bundle size). Open Peeps was not imported: its npm wrapper ships unreadable files.
 */
import fs from 'node:fs'
import path from 'node:path'
import { createRequire } from 'node:module'

const dir = process.argv[2]
if (!dir || !fs.existsSync(path.join(dir, 'dist/index.js'))) {
  console.error('usage: import-illustrations.mjs <react-open-doodles package dir>')
  process.exit(1)
}
if (!/^MIT License/.test(fs.readFileSync(path.join(dir, 'LICENSE'), 'utf8'))) {
  console.error('licence check failed: expected MIT')
  process.exit(1)
}
const here = path.dirname(new URL(import.meta.url).pathname)
const require = createRequire(path.join(here, '../../package.json'))
const React = require('react')
const { renderToStaticMarkup } = require('react-dom/server')
const doodles = require(path.resolve(dir, 'dist/index.js'))

// scene → [Vietnamese and English tags]
const TAGS = {
  Ballet: ['dance', 'múa', 'art', 'nghệ thuật'], Bikini: ['summer', 'mùa hè', 'beach', 'biển'], Chilling: ['relax', 'thư giãn', 'rest', 'nghỉ'],
  Clumsy: ['mistake', 'sai lầm', 'fall', 'lỗi'], Coffee: ['coffee', 'cà phê', 'break', 'giải lao'], Dancing: ['dance', 'nhảy', 'celebrate', 'vui'],
  DogJump: ['dog', 'chó', 'play', 'chơi'], Doggie: ['dog', 'chó', 'pet', 'thú cưng'], Float: ['dream', 'mơ', 'idea', 'ý tưởng'],
  Groovy: ['music', 'âm nhạc', 'fun', 'vui'], IceCream: ['ice cream', 'kem', 'treat', 'thưởng'], Jumping: ['success', 'thành công', 'joy', 'vui'],
  Laying: ['rest', 'nghỉ', 'phone', 'điện thoại'], Levitate: ['focus', 'tập trung', 'calm', 'bình tĩnh'], Loving: ['love', 'yêu', 'care', 'chăm sóc'],
  Meditating: ['meditation', 'thiền', 'calm', 'tĩnh tâm'], Moshing: ['energy', 'năng lượng', 'party', 'tiệc'], Petting: ['pet', 'thú cưng', 'care', 'chăm sóc'],
  Plant: ['plant', 'cây', 'growth', 'phát triển'], Reading: ['reading', 'đọc', 'study', 'học'], ReadingSide: ['reading', 'đọc sách', 'learn', 'học tập'],
  RollerSkating: ['skate', 'trượt', 'speed', 'nhanh'], Rolling: ['fun', 'vui', 'play', 'chơi'], Running: ['run', 'chạy', 'progress', 'tiến bộ'],
  Selfie: ['selfie', 'chụp ảnh', 'social', 'mạng xã hội'], Sitting: ['sit', 'ngồi', 'wait', 'chờ'], SittingReading: ['reading', 'đọc', 'student', 'học sinh'],
  Sleek: ['style', 'phong cách', 'confident', 'tự tin'], Sprinting: ['sprint', 'chạy nước rút', 'deadline', 'hạn chót'], Strolling: ['walk', 'đi bộ', 'journey', 'hành trình'],
  Swinging: ['swing', 'xích đu', 'balance', 'cân bằng'], Unboxing: ['unbox', 'mở hộp', 'new', 'mới', 'gift', 'quà'], Zombieing: ['tired', 'mệt', 'sleepy', 'buồn ngủ'],
}

// the scenes a lecture or a pitch uses (study, effort, success, a pause, an idea); the pack rides
// in the engine bundle, so the rest stay out
const KEEP = new Set(['Reading', 'ReadingSide', 'SittingReading', 'Sitting', 'Meditating', 'Levitate', 'Coffee', 'Chilling', 'Running', 'Sprinting', 'Strolling', 'Jumping', 'Unboxing', 'Loving', 'Zombieing'])

const INK = '#010203'
const ACCENT = '#040506'
const rows = []
for (const [exp, Comp] of Object.entries(doodles)) {
  if (!/Doodle$/.test(exp) || typeof Comp !== 'function') continue
  const scene = exp.replace(/Doodle$/, '')
  let svg = renderToStaticMarkup(React.createElement(Comp, { ink: INK, accent: ACCENT }))
  const vb = /viewBox="([^"]+)"/.exec(svg)?.[1]
  if (!vb) continue
  svg = svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>$/, '')
  svg = svg.replaceAll(INK, '{ink}').replaceAll(ACCENT, '{accent}').replace(/#fff(fff)?\b|white/gi, '{paper}')
  if (!KEEP.has(scene)) continue
  const name = scene.replace(/([a-z])([A-Z])/g, '$1-$2').toLowerCase()
  rows.push({ name, vb, svg, tags: TAGS[scene] ?? [] })
}
rows.sort((a, b) => a.name.localeCompare(b.name))
const lines = [
  '/**',
  ' * Generated by `tools/icons/import-illustrations.mjs` (spro creative PLAN CR9) — do not edit by hand.',
  ' * Open Doodles by Pablo Stanley, CC0 (https://www.opendoodles.com), via react-open-doodles 1.0.5',
  ' * (MIT License, Copyright (c) 2020 Luna). Colours are palette slots: {ink}, {accent}, {paper}.',
  ' */',
  '',
  "export const ILLUSTRATION_SOURCE = 'Open Doodles (Pablo Stanley), CC0 - https://www.opendoodles.com'",
  '',
  '/** name → [viewBox, SVG body with {ink} {accent} {paper} slots, tags (EN/VI)] */',
  'export const ILLUSTRATIONS: Record<string, [string, string, string[]]> = {',
  ...rows.map((r) => `  ${JSON.stringify(r.name)}: [${JSON.stringify(r.vb)}, ${JSON.stringify(r.svg)}, ${JSON.stringify(r.tags)}],`),
  '}',
  '',
]
const target = path.join(here, '../../packages/tldraw/src/blocks/icons/illustrations.ts')
fs.writeFileSync(target, lines.join('\n'))
console.log(`${rows.length} illustrations →`, target, `${Math.round(fs.statSync(target).size / 1024)} KB`)
