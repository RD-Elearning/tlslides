#!/usr/bin/env node
/**
 * spro sprint 2026-11b S05-A — regenerate the committed text budget table:
 *   node tools/text-budgets/cli.js            # writes packages/tldraw/src/blocks/__generated__/text-budgets.json
 *   node tools/text-budgets/cli.js --check    # exit 1 when the committed file is stale
 *   node tools/text-budgets/cli.js --types tls.c.cards,tls.t.bullets   # print, do not write
 * Every block with a fits row (rankable, not editor-only) × region class × language (`textBudgets.ts`).
 */
const fs = require('fs')
const path = require('path')
const { loadOracle, PKG } = require('../layout-report/load')

const OUT = path.join(PKG, 'src/blocks/__generated__/text-budgets.json')
const args = process.argv.slice(2)
const typesArg = args.includes('--types') ? args[args.indexOf('--types') + 1].split(',') : null
const t0 = Date.now()
const o = loadOracle()
const registry = o.defaultBlockRegistry()
const types = typesArg || registry.list().filter((d) => d.fits && !d.editorOnly).map((d) => d.type).sort()
const rows = o.textBudgets(types, registry)
const file = { note: 'generated by tools/text-budgets/cli.js (spro sprint 2026-11b S05-A); do not edit', classes: o.REGION_CLASSES, blocks: {} }
for (const r of rows) {
  const b = (file.blocks[r.type] = file.blocks[r.type] || {})
  const c = (b[r.cls] = b[r.cls] || {})
  c[r.lang] = { items: r.items, factor: r.factor, slots: r.slots }
}
const json = JSON.stringify(file, null, 1) + '\n'
if (typesArg) {
  process.stdout.write(json)
} else if (args.includes('--check')) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : ''
  if (cur !== json) {
    console.error('text-budgets.json is stale: node tools/text-budgets/cli.js')
    process.exit(1)
  }
  console.log('text-budgets.json is current')
} else {
  fs.writeFileSync(OUT, json)
  console.log(`wrote ${path.relative(process.cwd(), OUT)}: ${Object.keys(file.blocks).length} blocks, ${rows.length} rows, ${rows.filter((r) => !r.slots).length} do-not-fit, in ${Date.now() - t0} ms`)
}
